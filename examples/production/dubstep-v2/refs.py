#!/usr/bin/env python3
"""Measure the reference sounds (engine/third_party.json `refs-dubstep-cc0`, `refs-dubstep-ccby`; install with
`python3 tools/engine_assets.py install refs-dubstep-cc0 refs-dubstep-ccby`) and the engine's OLD and NEW version of
each role (sounds.py) with describe.py; write refs-numbers.json (every sound's descriptors: the references by id, no
audio) and tables.md (per role: reference median [p25, p75] against each engine sound).

    bash tools/remix/waitfree.sh render && python3 examples/production/dubstep-v2/refs.py      # about 2 minutes
"""
import json
import os
import re
import sys
import warnings

import numpy as np

warnings.filterwarnings("ignore")
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import describe as DS  # noqa: E402
import sounds as SO  # noqa: E402

CACHE = os.environ.get("SPECTRE_CACHE", os.path.expanduser("~/.cache/spectre"))
SUST = {"growl", "riddim", "wobble", "reese", "sub", "screech", "vocalchop", "riser", "downlifter"}
ROLES = ["growl", "riddim", "wobble", "reese", "sub", "screech", "snare", "clap", "kick", "hat", "vocalchop", "riser",
         "impact", "downlifter"]
KEYS = [("groups150_db", "lowmid 150-500"), ("groups150_db", "mid 500-2k"), ("groups150_db", "pres 2-5k"),
        ("groups150_db", "air 5-16k"), ("groups_db", "sub <60"), ("groups_db", "low 60-150"),
        ("groups_db", "lowmid 150-500"), ("groups_db", "mid 500-2k"), ("groups_db", "pres 2-5k"),
        ("groups_db", "air 5-16k"), ("tilt_db_oct", None), ("centroid_hz", None), ("centroid_move_oct", None),
        ("flatness", None), ("flatness_4k", None), ("hnr_db", None), ("even_odd_db", None), ("mod_rate_hz", None),
        ("mod_depth_db", None), ("crest_db", None), ("decay20_ms", "low"), ("decay20_ms", "mid"),
        ("decay20_ms", "high"), ("side_mid_db", "<150"), ("side_mid_db", "150-1k"), ("side_mid_db", "1-5k"),
        ("side_mid_db", ">5k"), ("lufs_m_max", None)]


def manifest_refs():
    m = json.load(open(os.path.join(SO.REPO, "engine", "third_party.json")))
    out = []
    for r in m["resources"]:
        if r["id"] in ("refs-dubstep-cc0", "refs-dubstep-ccby"):
            out += r["files"]
    return out


def bpm_of(title):
    mm = re.search(r"(\d{2,3})\s*bpm", title.lower())
    return float(mm.group(1)) if mm else 140.0


def get(d, k, s):
    v = d.get(k)
    return v.get(s) if s is not None and isinstance(v, dict) else v


def main():
    import librosa
    D = {"refs": [], "old": [], "new": []}
    for f in manifest_refs():
        p = os.path.join(CACHE, f["path"])
        if not os.path.exists(p):
            raise SystemExit(f"missing {p}: python3 tools/engine_assets.py install refs-dubstep-cc0 refs-dubstep-ccby")
        y, _ = librosa.load(p, sr=44100, mono=False)
        D["refs"].append(dict(role=f["role"], page=f["page"], licence=f["licence"], author=f["author"],
                              title=f["title"], d=DS.describe(y, bpm_of(f["title"]), f["role"] in SUST)))
    for key, fn in (("old", SO.old_sounds), ("new", SO.new_sounds)):
        for label, (role, x) in fn().items():
            D[key].append(dict(role=role, label=label, d=DS.describe(x, 140.0, role in SUST)))
    json.dump(D, open(os.path.join(HERE, "refs-numbers.json"), "w"), indent=1)
    lines = ["# Reference measurements against the engine (generated by refs.py)", "",
             "Reference: median [p25, p75] over the role's references (engine/third_party.json refs-dubstep-*). OLD: "
             "the engine before 2026-11-26's second pass (the dubstep A/B, session 017). NEW: the fitted presets and "
             "fx_model 2. Units in describe.py.", ""]
    for role in ROLES:
        R = [r["d"] for r in D["refs"] if r["role"] == role]
        E = [("OLD", e) for e in D["old"] if e["role"] == role] + [("NEW", e) for e in D["new"] if e["role"] == role]
        if not R:
            continue
        lines += [f"## {role} ({len(R)} references)", "",
                  "| metric | reference | " + " | ".join(f"{t} {e['label'].split(': ', 1)[1]}" for t, e in E) + " |",
                  "|---|---|" + "---|" * len(E)]
        for k, s in KEYS:
            vals = [v for v in (get(d, k, s) for d in R) if isinstance(v, (int, float)) and np.isfinite(v)]
            if not vals:
                continue
            med, a, b = np.median(vals), np.percentile(vals, 25), np.percentile(vals, 75)
            ev = [get(e["d"], k, s) for _, e in E]
            lines.append(f"| {k}{f'[{s}]' if s else ''} | {med:.3g} [{a:.3g}, {b:.3g}] | " + " | ".join(
                "-" if v is None else f"{v:.3g}" for v in ev) + " |")
        lines.append("")
    open(os.path.join(HERE, "tables.md"), "w").write("\n".join(lines))
    print("wrote refs-numbers.json and tables.md")


if __name__ == "__main__":
    main()
